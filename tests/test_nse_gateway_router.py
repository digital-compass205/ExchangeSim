"""The Gateway Router leg: ``GR_REQUEST``/``GR_RESPONSE``, and the TLS wrapper
Phase 4 put around it.

There was no unit test for this listener before this file: ``nsesupport``'s
default config disables the router (``"gateway_router": {"enabled": False}``),
because every other NSE test drives a box straight through
:class:`exchangesim.nnf.session.BoxConnection` rather than through a real
socket. Here the router is enabled and driven for real, on the venue's own
reactor, since ``GatewayRouter`` -- unlike a box connection -- is a genuine
:class:`exchangesim.core.reactor.Listener` with no fake-transport seam.

Two client shapes are used, matching how each policy needs to be driven:

* At policy ``"none"`` a blocking client socket plus :func:`tests.support.pump`
  is enough -- the same pattern :mod:`tests.test_fix_acceptor` uses for the
  FIX acceptor, and just as free of threads and sleeps.
* At policy ``"1.2"`` the conversation must ride a real TLS handshake, which
  needs a *non-blocking* client so the reactor can service both ends of the
  loopback connection itself: :meth:`exchangesim.core.reactor.Reactor.connect`
  with a :class:`exchangesim.tls.transport.TlsTransport`, pumped with
  :func:`tests.support.pump_until` exactly as the task describes.

Certificates are generated **once**, at module scope, into a ``tempfile``
directory rather than the repository's own ``var/`` -- RSA-2048 keygen is the
slow part of any TLS test here (see ``tests/test_tls_transport.py``'s module
docstring), and every ``"1.2"`` test in this file points its venue at the same
pre-populated ``tls_dir`` so ``CertificateStore.ensure()`` finds a matching,
unexpired certificate already on disk and never regenerates one.
"""

