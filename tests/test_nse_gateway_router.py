class PlainRouterTest(unittest.TestCase):

    def setUp(self):
        self.harness = VenueHarness(gr_config(tls="none"))
        self.addCleanup(self.harness.close)
        self.address = self.harness.venue.router.address

    def _client(self):
        client = GrBlockingClient(self.address, self.harness.venue.layouts)
        self.addCleanup(client.close)
        return client

    def test_a_configured_box_is_granted_secrets(self):
        client = self._client()
        client.request(BOX_ONE, BROKER_ONE)
        pump(self.harness.reactor)

        received = client.receive()

        self.assertEqual(1, len(received))
        response = received[0]
        self.assertEqual(str(X.GR_RESPONSE), response.msg_type)
        self.assertEqual(str(X.NO_ERROR), response.get(D.ERROR_CODE))
        self.assertEqual(
            list(self.harness.venue.acceptor.address[:2]),
            [response.get(D.IP_ADDRESS), int(response.get(D.PORT))])

        secrets = self.harness.venue.issued(BOX_ONE)
        self.assertIsNotNone(secrets)
        self.assertEqual(secrets.session_key, response.get(D.SESSION_KEY))

    def test_a_box_disconnecting_discards_what_it_was_issued(self):
        """The document resets the IVs at the exchange on a box disconnection
        and expects a fresh GR query for the next connection. Holding them
        would hand a cipher to a box that reconnected without dialling the
        router, garbling the connection rather than refusing it -- and, with
        require_encryption off, making a plain reconnect impossible on any box
        that had ever collected a key."""
        client = self._client()
        client.request(BOX_ONE, BROKER_ONE)
        pump(self.harness.reactor)
        self.assertIsNotNone(self.harness.venue.issued(BOX_ONE))

        member = BoxClient(self.harness.venue, BOX_ONE, BROKER_ONE)
        member.box.detach("test")

        self.assertIsNone(self.harness.venue.issued(BOX_ONE))

    def test_an_unconfigured_box_is_refused(self):
        client = self._client()
        client.request(UNKNOWN_BOX, BROKER_ONE)
        pump(self.harness.reactor)

        response = client.receive()[0]
        self.assertEqual(USER_IP_REC_NOT_FOUND, response.get(D.ERROR_CODE))
        self.assertIsNone(self.harness.venue.issued(UNKNOWN_BOX))

    def test_a_box_dialling_with_the_wrong_broker_is_refused(self):
        client = self._client()
        client.request(BOX_ONE, BROKER_TWO)
        pump(self.harness.reactor)

        response = client.receive()[0]
        self.assertEqual(INVALID_BROKER_OR_BRANCH, response.get(D.ERROR_CODE))

    def test_anything_but_a_gr_request_closes_the_connection(self):
        client = self._client()
        client.send_other(X.BOX_SIGN_ON_REQUEST_IN,
                          {D.BOX_ID: BOX_ONE, D.BROKER_ID: BROKER_ONE})
        pump(self.harness.reactor)

        self.assertEqual([], client.receive())
        self.assertTrue(client.eof())

    def test_the_conversation_is_audited_with_credentials_redacted(self):
        client = self._client()
        client.request(BOX_ONE, BROKER_ONE)
        pump(self.harness.reactor)
        client.receive()

        entries = self.harness.venue.audit.entries(limit=50).entries
        request_entry = [e for e in entries if e.type == str(X.GR_REQUEST)][0]
        response_entry = [e for e in entries if e.type == str(X.GR_RESPONSE)][0]
        self.assertEqual("nnf", request_entry.protocol)
        self.assertEqual("nnf", response_entry.protocol)
        self.assertEqual("in", request_entry.direction)
        self.assertEqual("out", response_entry.direction)

        opened = self.harness.command("audit.entry", seq=response_entry.seq)
        redacted = dict((row["name"], row["redacted"])
                       for row in opened["fields"])
        for name in ("SessionKey", "CryptographicKey",
                     "StaticCryptographicIV", "DynamicCryptographicIV",
                     "CryptographicAdditionalKey"):
            self.assertTrue(redacted[name], name)
        values = dict((row["name"], row["value"]) for row in opened["fields"])
        for name in redacted:
            if redacted[name]:
                self.assertEqual(REDACTED, values[name])


