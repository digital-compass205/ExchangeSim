class Tls13UnavailableTest(unittest.TestCase):

    def test_tls13_is_refused_at_startup_on_an_old_openssl(self):
        if ssl.HAS_TLSv1_3:
            self.skipTest(
                "this interpreter's OpenSSL (%s) supports TLS 1.3, so '1.3' "
                "cannot be shown unavailable here" % ssl.OPENSSL_VERSION)

        # Bogus, non-existent paths: _pin_version raises TlsUnavailable before
        # context.server_context ever tries to open a certificate file, so
        # this never touches disk and pays no keygen cost.
        config = gr_config(tls="1.3", tls_cert="/no/such/cert.pem",
                          tls_key="/no/such/key.pem")

        with self.assertRaises(ConfigError) as caught:
            VenueHarness(config)

        message = str(caught.exception)
        self.assertEqual(
            context.describe_unavailable("1.3", setting_name="gateway_router.tls"),
            message)
        self.assertIn("gateway_router.tls", message)
        self.assertIn("1.2", message)
        self.assertIn("none", message)


