# ---------------------------------------------------------------------------
# Certificate fixture: built once, on import, never regenerated by a test.
# ---------------------------------------------------------------------------

def _build_fixture():
    tls_dir = tempfile.mkdtemp(prefix="exsim-nse-gr-")
    # Matches exactly what NseVenue._build_tls asks for when
    # gateway_router.host is "127.0.0.1" and no tls_names override is given:
    # common_name=host, names=(host, "localhost") after de-duplication. Same
    # parameters here means the venue's own CertificateStore.ensure() call
    # finds this fixture's files already good and never re-generates them.
    store = certs.CertificateStore(tls_dir, common_name="127.0.0.1",
                                   names=("127.0.0.1", "localhost"))
    issued = store.ensure()

    wrong_dir = tempfile.mkdtemp(prefix="exsim-nse-gr-wrong-")
    wrong_key = rsa.generate(2048)
    wrong_ca_der = x509.self_signed_ca(
        wrong_key, "A Different CA", "ExchangeSim", days=3650, serial=1,
        now=datetime.datetime(2026, 1, 1))
    wrong_ca_pem = wrong_dir + "/wrong-ca.pem"
    with open(wrong_ca_pem, "wb") as handle:
        handle.write(rsa.to_pem(wrong_ca_der, "CERTIFICATE").encode("ascii"))

    return tls_dir, wrong_dir, issued, wrong_ca_pem


_TLS_DIR, _WRONG_DIR, _ISSUED, _WRONG_CA_PEM = _build_fixture()
_CA_PEM = _ISSUED.ca_certificate

atexit.register(shutil.rmtree, _TLS_DIR, True)
atexit.register(shutil.rmtree, _WRONG_DIR, True)


def _strings_in(value):
    """Every string reachable inside a nested dict/list/tuple structure."""
    if isinstance(value, dict):
        for item in value.values():
            for found in _strings_in(item):
                yield found
    elif isinstance(value, (list, tuple)):
        for item in value:
            for found in _strings_in(item):
                yield found
    elif isinstance(value, str):
        yield value


def gr_config(**router):
    """A venue config with the Gateway Router enabled on an OS-chosen port."""
    settings = {"enabled": True, "host": "127.0.0.1", "port": 0,
                "encryption": "new"}
    settings.update(router)
    return venue_config(gateway_router=settings)


# ---------------------------------------------------------------------------
# A blocking client, for the un-encrypted conversation
# ---------------------------------------------------------------------------

class GrBlockingClient(object):
    """A blocking client socket that speaks just enough NNF for the router."""

    def __init__(self, address, layouts):
        self.sock = connect(address)
        self.codec = NnfCodec(layouts, client=True)
        self._framer = self.codec.framer()

    def request(self, box_id, broker_id):
        message = Message.create(str(X.GR_REQUEST))
        message.set(D.ERROR_CODE, "0")
        message.set(D.BOX_ID, str(box_id))
        message.set(D.BROKER_ID, broker_id)
        self.sock.sendall(self.codec.encode(message))
        return message

    def send_other(self, code, fields):
        message = Message.create(str(code))
        message.set(D.ERROR_CODE, "0")
        for tag, value in sorted((fields or {}).items()):
            message.set(tag, str(value))
        self.sock.sendall(self.codec.encode(message))
        return message

    def receive(self, timeout=0.5):
        self.sock.settimeout(timeout)
        try:
            chunk = self.sock.recv(65536)
        except socket.timeout:
            return []
        if not chunk:
            return []
        return [self.codec.decode(raw) for raw in self._framer.feed(chunk)]

    def eof(self, timeout=0.5):
        """Whether the peer has closed the connection."""
        self.sock.settimeout(timeout)
        try:
            chunk = self.sock.recv(65536)
        except socket.timeout:
            return False
        return chunk == b""

    def close(self):
        try:
            self.sock.close()
        except OSError:
            pass


# ---------------------------------------------------------------------------
# A non-blocking, reactor-driven client, for the TLS conversation
# ---------------------------------------------------------------------------

class GrReactorClient(object):
    """One Gateway Router conversation driven on the venue's own reactor."""

    def __init__(self, reactor, address, layouts, transport=None):
        self.codec = NnfCodec(layouts, client=True)
        self._framer = self.codec.framer()
        self.received = []
        self.closed = False
        self.conn = reactor.connect(address[0], address[1],
                                    self._on_connect, self._on_error,
                                    transport=transport)
        self.conn.on_data = self._on_data
        self.conn.on_close = self._on_close

    def _on_connect(self, conn):
        pass

    def _on_error(self, conn, exc):
        pass

    def _on_data(self, conn, chunk):
        for raw in self._framer.feed(chunk):
            self.received.append(self.codec.decode(raw))

    def _on_close(self, conn):
        self.closed = True

    def request(self, box_id, broker_id):
        message = Message.create(str(X.GR_REQUEST))
        message.set(D.ERROR_CODE, "0")
        message.set(D.BOX_ID, str(box_id))
        message.set(D.BROKER_ID, broker_id)
        self.conn.send(self.codec.encode(message))
        return message


