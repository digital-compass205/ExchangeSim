class Tls12RouterTest(unittest.TestCase):

    def setUp(self):
        self.harness = VenueHarness(
            gr_config(tls="1.2", tls_dir=_TLS_DIR))
        self.addCleanup(self.harness.close)
        self.address = self.harness.venue.router.address
        self.reactor = self.harness.reactor

    def _client_context(self, cafile=_CA_PEM):
        return context.client_context("1.2", cafile)

    def test_the_conversation_completes_over_a_real_handshake(self):
        transport = TlsTransport(self._client_context(), server_side=False,
                                 server_hostname="127.0.0.1")
        client = GrReactorClient(self.reactor, self.address,
                                 self.harness.venue.layouts,
                                 transport=transport)
        client.request(BOX_ONE, BROKER_ONE)

        completed = pump_until(self.reactor, lambda: len(client.received) >= 1)
        self.assertTrue(completed, "no GR_RESPONSE arrived over TLS")

        response = client.received[0]
        self.assertEqual(str(X.GR_RESPONSE), response.msg_type)
        self.assertEqual(str(X.NO_ERROR), response.get(D.ERROR_CODE))
        secrets = self.harness.venue.issued(BOX_ONE)
        self.assertEqual(secrets.session_key, response.get(D.SESSION_KEY))

    def test_a_client_trusting_the_wrong_ca_is_dropped(self):
        transport = TlsTransport(self._client_context(cafile=_WRONG_CA_PEM),
                                 server_side=False,
                                 server_hostname="127.0.0.1")
        client = GrReactorClient(self.reactor, self.address,
                                 self.harness.venue.layouts,
                                 transport=transport)
        client.request(BOX_ONE, BROKER_ONE)

        pump_until(self.reactor,
                  lambda: client.closed or len(client.received) >= 1)

        self.assertTrue(client.closed)
        self.assertEqual([], client.received)

    def test_gateway_router_command_reports_ca_and_fingerprint_but_no_key(self):
        result = self.harness.command("gateway_router")

        self.assertEqual("1.2", result["tls"])
        self.assertEqual(_CA_PEM, result["ca_certificate"])
        self.assertIsNotNone(result["fingerprint"])
        self.assertIsNotNone(result["certificate_expires"])

        for text in _strings_in(result):
            self.assertNotIn("BEGIN", text)
            for component in text.replace("\\", "/").split("/"):
                self.assertNotIn("key", component.lower())


